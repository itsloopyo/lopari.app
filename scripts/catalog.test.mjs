  const { site, readmePath } = workspace(t, [{ ...wobbly, added: daysAgo(7) }]);
  execFileSync(process.execPath, [join(site, "scripts", "generate-readme.mjs")]);
  assert.equal(recentList(readFileSync(readmePath, "utf8")), "No new mods this week.");
