const scripts = dirname(fileURLToPath(import.meta.url));
const begin = "<!-- BEGIN MOD TABLE (generated by lopari.app: pixi run update-metadata) -->";
const end = "<!-- END MOD TABLE -->";
const recentBegin = "<!-- BEGIN NEW ADDITIONS (generated by lopari.app: pixi run update-metadata) -->";
const recentEnd = "<!-- END NEW ADDITIONS -->";
const daysAgo = (n) => new Date(Date.now() - n * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);
const recentList = (output) =>
  output.slice(output.indexOf(recentBegin) + recentBegin.length, output.indexOf(recentEnd)).trim();
const readme = `Handwritten introduction\n${recentBegin}\nold list\n${recentEnd}\nHandwritten middle\n${begin}\nold table\n${end}\nHandwritten footer\n`;
const wobbly = {
  id: "wobbly-life", display_name: "Wobbly Life", repo: "itsloopyo/wobbly-life-headtracking",
  public: true, released: false, added: "2026-05-28", install_strategy: "BepInEx5",
  verified_sources: ["Steam", "Xbox"],
  game: { steam_app_id: 1211020, executable_relpath: "Wobbly Life.exe" },
  known_issues: ["Not comprehensively tested."],
  distribution: { type: "dev-release", pinned: {
    version: "0.0.0-nightly.old", built_at: "2026-09-01T00:00:00Z",
    zip_filename: "WobblyLifeHeadTracking-dev-installer.zip",
    download_url: "https://github.com/itsloopyo/wobbly-life-headtracking/releases/download/dev/WobblyLifeHeadTracking-dev-installer.zip",
  } },
};

const staleRelease = {
  pinned: {
    version: "1.0.0", tag_name: "v1.0.0",
    zip_filename: "WobblyLifeHeadTracking-installer.zip",
    download_url: "https://github.com/itsloopyo/wobbly-life-headtracking/releases/download/v1.0.0/WobblyLifeHeadTracking-installer.zip",
  },
  versions: [{ version: "1.0.0", tag_name: "v1.0.0" }],
};

function workspace(t, mods) {
  const root = mkdtempSync(join(tmpdir(), "lopari-catalog-test-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const site = join(root, "lopari.app");
  mkdirSync(join(site, "scripts"), { recursive: true });
  mkdirSync(join(root, "lopari", "catalog"), { recursive: true });
  mkdirSync(join(root, "itsloopyo"));
  for (const script of ["update-metadata.mjs", "generate-readme.mjs", "generate-feed.mjs"]) {
    copyFileSync(join(scripts, script), join(site, "scripts", script));
  }
  const catalog = { schema_version: 2, mods, native_games: [] };
  writeFileSync(join(site, "mods.json"), JSON.stringify(catalog));
  writeFileSync(join(root, "lopari", "catalog", "mods.json"), JSON.stringify(catalog));
  writeFileSync(join(root, "itsloopyo", "README.md"), readme);
  return {
    root, site,
    readmePath: join(root, "itsloopyo", "README.md"),
    feedPath: join(site, "feed.xml"),
  };
}

test("README lists verified stores without inferring support from detection", (t) => {
  const mods = [
    wobbly,
    { ...wobbly, id: "steam", display_name: "Steam only", verified_sources: ["Steam"],
      game: { gog_ids: ["123"], xbox_paths: ["example"] } },
    { ...wobbly, id: "labels", display_name: "Store labels",
      verified_sources: ["Gog", "Epic", "Msix", "Ea", "Ubisoft", "Manual"] },
    { ...wobbly, id: "empty", display_name: "Empty stores", verified_sources: [] },
    { ...wobbly, id: "absent", display_name: "Absent stores", verified_sources: undefined },
    { ...wobbly, id: "private", display_name: "Private mod", public: false },
    { ...wobbly, id: "external", display_name: "External mod", install_strategy: "External",
      release: { versions: [{ version: "1.2.3", published_at: "2026-09-02T00:00:00Z" }] } },
  ];
  const { site, readmePath } = workspace(t, mods);
  execFileSync(process.execPath, [join(site, "scripts", "generate-readme.mjs")]);
  const output = readFileSync(readmePath, "utf8");
  assert.ok(output.startsWith(`Handwritten introduction\n${recentBegin}\n`));
  assert.ok(output.includes(`${recentEnd}\nHandwritten middle\n${begin}\n`));
  assert.ok(output.endsWith(`${end}\nHandwritten footer\n`));
  assert.ok(output.includes("| Game | Status | Supported stores | Links | Latest release |"));
  assert.ok(output.includes("| Wobbly Life | Beta | Steam, Xbox |"));
  assert.ok(output.includes("| Steam only | Beta | Steam |"));
  assert.ok(output.includes("| Store labels | Beta | GOG, Epic, Microsoft Store, EA app, Ubisoft Connect, Manual |"));
  assert.ok(output.includes("| Empty stores | Beta | Not specified |"));
  assert.ok(output.includes("| Absent stores | Beta | Not specified |"));
  assert.ok(output.includes("| External mod | Released | Steam, Xbox |"));
  assert.ok(!output.includes("Private mod"));
  for (const row of output.split("\n").filter(line => line.startsWith("|"))) {
    assert.equal(row.split("|").length, 7);
  }
  execFileSync(process.execPath, [join(site, "scripts", "generate-readme.mjs")]);
  assert.equal(readFileSync(readmePath, "utf8"), output);
});

test("README lists every mod added this week, newest first", (t) => {
  const mods = [
    { ...wobbly, id: "today", display_name: "Today", added: daysAgo(0) },
    { ...wobbly, id: "same-day", display_name: "Also today", added: daysAgo(0) },
    { ...wobbly, id: "edge", display_name: "Six days", added: daysAgo(6) },
    { ...wobbly, id: "old", display_name: "Seven days", added: daysAgo(7) },
    { ...wobbly, id: "private", display_name: "Private mod", public: false, added: daysAgo(1) },
  ];
  const { site, readmePath } = workspace(t, mods);
  execFileSync(process.execPath, [join(site, "scripts", "generate-readme.mjs")]);
  const repo = "[GitHub](https://github.com/itsloopyo/wobbly-life-headtracking)";
  assert.deepEqual(recentList(readFileSync(readmePath, "utf8")).split("\n"), [
    `- **Also today** (Beta), added ${daysAgo(0)} · ${repo}`,
    `- **Today** (Beta), added ${daysAgo(0)} · ${repo}`,
    `- **Six days** (Beta), added ${daysAgo(6)} · ${repo}`,
  ]);
});

